/// Generates the preflop range set of ``BaselineStrategy`` as an equity-realisation fixed point, and writes it as
/// Swift source. Library side of `allin-tool gen-preflop-ranges`.
public enum BaselineRangeModel {
  /// Runs the fixed point: opening ranges against what the players behind defend, defences against the opening
  /// ranges, re-raises and their answers, each range damped against the previous round.
  /// - Parameters:
  ///   - seed: seeds every Monte Carlo class-versus-range equity (deterministic for a fixed seed).
  ///   - samplesPerClass: Monte Carlo samples per hand class and range (the tool default is 1500).
  public static func generate(seed: UInt64, samplesPerClass: Int) -> BaselinePreflopRanges {
    generate(seed: seed, samplesPerClass: samplesPerClass, rounds: Solver.rounds)
  }

  /// `generate` with a chosen number of fixed-point rounds (fewer rounds are cheaper and cruder; for tests).
  static func generate(seed: UInt64, samplesPerClass: Int, rounds: Int) -> BaselinePreflopRanges {
    var ranges: [String: HandRange] = [:]
    for layout in [Layout.sixMax, Layout.headsUp] {
      var solver = Solver(layout: layout, seed: seed, samples: max(samplesPerClass, 1), rounds: max(rounds, 0))
      solver.run()
      solver.export(into: &ranges)
    }
    return BaselinePreflopRanges(ranges: ranges)
  }

  /// Lint-clean Swift source of `BaselinePreflopRanges.generatedText`: range text in literal chunks of at most
  /// 90 characters (joined with ", " when loaded), keys sorted.
  public static func swiftSource(for ranges: BaselinePreflopRanges) -> String {
    var out = "// Generated by `allin-tool gen-preflop-ranges`. Do not edit by hand.\n\n"
    out += "extension BaselinePreflopRanges {\n"
    out += "  static let generatedText: [String: [String]] = [\n"
    for key in ranges.ranges.keys.sorted() {
      out += "    \"\(key)\": [\n"
      let pieces = chunks(of: ranges.ranges[key]?.text ?? "")
      // swift-format drops the trailing comma of a one-element array.
      for chunk in pieces {
        out += "      \"\(chunk)\"\(pieces.count > 1 ? "," : "")\n"
      }
      out += "    ],\n"
    }
    out += "  ]\n"
    out += "}\n"
    return out
  }

  /// Splits range text at ", " into pieces of at most `limit` characters (a single token is never cut).
  static func chunks(of text: String, limit: Int = 90) -> [String] {
    let tokens = text.components(separatedBy: ", ").filter { !$0.isEmpty }
    guard !tokens.isEmpty else { return [""] }
    var result: [String] = []
    var current = ""
    for token in tokens {
      if current.isEmpty {
        current = token
      } else if current.count + 2 + token.count <= limit {
        current += ", " + token
      } else {
        result.append(current)
        current = token
      }
    }
    result.append(current)
    return result
  }
}

// MARK: - Model

private typealias ClassVector = [Double]

/// Posted blind, postflop order and name of one seat in action order.
private struct SeatSpec {
  let position: TablePosition
  let posted: Double
  /// Postflop acting order, 0 first.
  let postflopRank: Int
}

private struct Layout {
  let headsUp: Bool
  /// In preflop action order; the last seat is the big blind.
  let seats: [SeatSpec]

  static let sixMax = Layout(
    headsUp: false,
    seats: [
      SeatSpec(position: .early, posted: 0, postflopRank: 2),
      SeatSpec(position: .middle, posted: 0, postflopRank: 3),
      SeatSpec(position: .cutoff, posted: 0, postflopRank: 4),
      SeatSpec(position: .button, posted: 0, postflopRank: 5),
      SeatSpec(position: .smallBlind, posted: 0.5, postflopRank: 0),
      SeatSpec(position: .bigBlind, posted: 1, postflopRank: 1),
    ])

  static let headsUp = Layout(
    headsUp: true,
    seats: [
      SeatSpec(position: .button, posted: 0.5, postflopRank: 1),
      SeatSpec(position: .bigBlind, posted: 1, postflopRank: 0),
    ])

  /// Equity realisation of `hero` against `villain`.
  func realization(hero: Int, villain: Int) -> Double {
    if headsUp { return hero == 1 ? Solver.realizationHeadsUpBlind : Solver.realizationIP }
    return seats[hero].postflopRank > seats[villain].postflopRank ? Solver.realizationIP : Solver.realizationOOP
  }
}

private struct Solver {
  static let realizationIP = 1.0
  static let realizationOOP = 0.82
  static let realizationHeadsUpBlind = 0.85
  static let rounds = 4
  static let damping = 0.5
  /// Each additional defender behind an opener takes this share off the equity of the called pot.
  static let multiwayPenalty = 0.01
  /// Realisation falls linearly with the hand's preflop percentile: the weakest hands realise `1 - slope` of it.
  static let qualitySlope = 0.35
  static let openSize = 2.5
  static let threeBetIP = 3.0
  static let threeBetOOP = 4.0
  static let fourBetMultiple = 2.3
  static let blinds = 1.5
  static let bluffNames = ["A5s", "A4s", "A3s", "A2s", "98s", "87s", "76s", "65s", "54s", "T9s"]

  let layout: Layout
  let seed: UInt64
  let samples: Int
  let rounds: Int
  private var count: Int { layout.seats.count }

  // Strategy vectors, by seat index (and opener index).
  private var open: [ClassVector?]
  private var defendCall: [[ClassVector?]]
  private var defendRaise: [[ClassVector?]]
  private var threeBetCall: [ClassVector?]
  private var threeBetRaise: [ClassVector?]
  private var threeBetEquity: [ClassVector?]
  private var threeBetSize: [Double]
  private var threeBetDead: [Double]
  private var threeBetRealization: [Double]
  private var fourBetCall: ClassVector?
  private var fourBetRaise: ClassVector?
  private var tag: UInt64 = 0

  init(layout: Layout, seed: UInt64, samples: Int, rounds: Int) {
    self.layout = layout
    self.rounds = rounds
    self.seed = seed
    self.samples = samples
    let n = layout.seats.count
    open = [ClassVector?](repeating: nil, count: n)
    defendCall = [[ClassVector?]](repeating: [ClassVector?](repeating: nil, count: n), count: n)
    defendRaise = defendCall
    threeBetCall = [ClassVector?](repeating: nil, count: n)
    threeBetRaise = threeBetCall
    threeBetEquity = threeBetCall
    threeBetSize = [Double](repeating: 0, count: n)
    threeBetDead = threeBetSize
    threeBetRealization = threeBetSize
  }

  // MARK: Fixed point

  mutating func run() {
    let model = LineRangeModel.standard
    for o in 0..<(count - 1) {
      let fraction: Double
      if layout.headsUp {
        fraction = model.headsUpButtonOpen
      } else {
        fraction = model.open[layout.seats[o].position] ?? 0.2
      }
      open[o] = vector(of: HandRange.top(fraction))
    }
    stepDefend()
    stepThreeBet()
    stepFourBet()
    for _ in 0..<rounds {
      stepOpen()
      stepDefend()
      stepThreeBet()
      stepFourBet()
    }
  }

  /// Opening: raise when the expected gain over folding is positive. The defenders behind fold, call or 3-bet;
  /// the opener's answer to a 3-bet comes from the previous round.
  private mutating func stepOpen() {
    for o in 0..<(count - 1) {
      let behind = Array((o + 1)..<count)
      var calls: [ClassVector] = []
      var callFrequencies: [Double] = []
      var callFrequency = 0.0
      var raiseFrequency = 0.0
      var foldEquity = 1.0
      var callRealization = 0.0
      for d in behind {
        let call = defendCall[d][o] ?? zeros
        let fc = share(of: call)
        let f3 = share(of: defendRaise[d][o] ?? zeros)
        calls.append(call)
        callFrequencies.append(fc)
        callFrequency += fc
        raiseFrequency += f3
        foldEquity *= 1 - min(fc + f3, 1)
        callRealization += fc * layout.realization(hero: o, villain: d)
      }
      let continuing = max(callFrequency + raiseFrequency, 1e-9)
      let callWeight = (1 - foldEquity) * callFrequency / continuing
      let raiseWeight = (1 - foldEquity) * raiseFrequency / continuing
      callRealization /= max(callFrequency, 1e-9)
      callRealization *= 1 - Solver.multiwayPenalty * Double(behind.count - 1)
      let equity = callFrequency > 0 ? equities(versus: mixture(calls, callFrequencies), id: nextTag()) : zeros
      let posted = layout.seats[o].posted
      let dead = Solver.blinds - posted
      let openCost = Solver.openSize - posted
      var target = ClassVector(repeating: 0, count: 169)
      for g in 0..<169 {
        let called = equity[g] * callRealization * Classes.quality[g] * (2 * Solver.openSize + dead) - openCost
        var threeBet = -openCost
        if let eq3 = threeBetEquity[o] {
          let keep = min((threeBetCall[o]?[g] ?? 0) + (threeBetRaise[o]?[g] ?? 0), 1)
          let size = threeBetSize[o]
          let played =
            eq3[g] * threeBetRealization[o] * Classes.quality[g] * (2 * size + threeBetDead[o]) - size + posted
          threeBet = keep * played + (1 - keep) * -openCost
        }
        let ev = foldEquity * Solver.blinds + callWeight * called + raiseWeight * threeBet
        target[g] = ev > 0 ? 1 : 0
      }
      open[o] = damp(open[o], target)
    }
  }

  /// Defence against each opening range: call, or re-raise (3-bet).
  private mutating func stepDefend() {
    for o in 0..<(count - 1) {
      guard let opening = open[o] else { continue }
      let equity = equities(versus: normalized(opening), id: nextTag())
      let postedOpener = layout.seats[o].posted
      for d in (o + 1)..<count {
        let c = Solver.openSize - layout.seats[d].posted
        let potBefore = Solver.openSize + Solver.blinds - postedOpener
        let r = layout.realization(hero: d, villain: o)
        var continuing = ClassVector(repeating: 0, count: 169)
        for g in 0..<169 where equity[g] * r * Classes.quality[g] * (potBefore + c) - c > 0 { continuing[g] = 1 }
        let (call, raise) = split(continuing, equity: equity)
        defendCall[d][o] = damp(defendCall[d][o], call)
        defendRaise[d][o] = damp(defendRaise[d][o], raise)
      }
    }
  }

  /// The opener against a 3-bet: call, or 4-bet.
  private mutating func stepThreeBet() {
    for o in 0..<(count - 1) {
      guard let opening = open[o] else { continue }
      var ranges: [ClassVector] = []
      var frequencies: [Double] = []
      var size = 0.0
      var posted = 0.0
      var realization = 0.0
      for j in (o + 1)..<count {
        let range = defendRaise[j][o] ?? zeros
        let f = share(of: range)
        ranges.append(range)
        frequencies.append(f)
        let inPosition = layout.seats[j].postflopRank > layout.seats[o].postflopRank
        size += f * Solver.openSize * (inPosition ? Solver.threeBetIP : Solver.threeBetOOP)
        posted += f * layout.seats[j].posted
        realization += f * layout.realization(hero: o, villain: j)
      }
      let total = max(frequencies.reduce(0, +), 1e-9)
      size /= total
      posted /= total
      realization /= total
      let equity = equities(versus: mixture(ranges, frequencies), id: nextTag())
      let dead = max(0, Solver.blinds - layout.seats[o].posted - posted)
      var continuing = ClassVector(repeating: 0, count: 169)
      for g in 0..<169 where opening[g] > 0.05 {
        if equity[g] * realization * Classes.quality[g] * (2 * size + dead) - (size - Solver.openSize) > 0 {
          continuing[g] = 1
        }
      }
      let (call, raise) = split(continuing, equity: equity)
      threeBetEquity[o] = equity
      threeBetSize[o] = size
      threeBetDead[o] = dead
      threeBetRealization[o] = realization
      threeBetCall[o] = damp(threeBetCall[o], call)
      threeBetRaise[o] = damp(threeBetRaise[o], raise)
    }
  }

  /// The 3-bettor against a 4-bet: call, or 5-bet all-in.
  private mutating func stepFourBet() {
    var ranges: [ClassVector] = []
    var frequencies: [Double] = []
    for o in 0..<(count - 1) {
      let range = threeBetRaise[o] ?? zeros
      ranges.append(range)
      frequencies.append(share(of: range))
    }
    let equity = equities(versus: mixture(ranges, frequencies), id: nextTag())
    let threeBet = Solver.openSize * 3.5
    let four = threeBet * Solver.fourBetMultiple
    let r = layout.headsUp ? Solver.realizationHeadsUpBlind : 0.9
    var continuing = ClassVector(repeating: 0, count: 169)
    for g in 0..<169 where equity[g] * r * Classes.quality[g] * (2 * four + 1) - (four - threeBet) > 0 {
      continuing[g] = 1
    }
    let (call, raise) = split(continuing, equity: equity)
    fourBetCall = damp(fourBetCall, call)
    fourBetRaise = damp(fourBetRaise, raise)
  }

  // MARK: Range helpers

  private var zeros: ClassVector { ClassVector(repeating: 0, count: 169) }

  private mutating func nextTag() -> UInt64 {
    tag += 1
    return tag
  }

  private func damp(_ old: ClassVector?, _ target: ClassVector) -> ClassVector {
    guard let old else { return target }
    return zip(old, target).map { Solver.damping * $0 + (1 - Solver.damping) * $1 }
  }

  /// Share of all 1326 combos in the class weights.
  private func share(of vector: ClassVector) -> Double {
    var total = 0.0
    for g in 0..<169 { total += vector[g] * Double(Classes.combos[g]) }
    return total / 1326
  }

  /// Per-class weights scaled so the largest is 1.
  private func normalized(_ vector: ClassVector) -> ClassVector {
    let top = vector.max() ?? 0
    return top > 0 ? vector.map { $0 / top } : vector
  }

  /// Frequency-weighted mix of ranges, as one range with the largest class weight 1.
  private func mixture(_ ranges: [ClassVector], _ frequencies: [Double]) -> ClassVector {
    var mixed = zeros
    for (range, f) in zip(ranges, frequencies) where f > 0 {
      let total = share(of: range) * 1326
      guard total > 0 else { continue }
      for g in 0..<169 { mixed[g] += f * range[g] * Double(Classes.combos[g]) / total }
    }
    for g in 0..<169 { mixed[g] /= Double(Classes.combos[g]) }
    let top = mixed.max() ?? 0
    return top > 0 ? mixed.map { $0 / top } : normalized(ranges.first ?? zeros)
  }

  /// Splits a continuing range into value re-raises (the top third by equity), blocker bluffs (half the value
  /// count, taken from the continuing suited aces and suited connectors) and calls.
  private func split(_ continuing: ClassVector, equity: [Double]) -> (call: ClassVector, raise: ClassVector) {
    let members = (0..<169).filter { continuing[$0] > 0 }.sorted {
      equity[$0] != equity[$1] ? equity[$0] > equity[$1] : $0 < $1
    }
    let totalCombos = members.reduce(0) { $0 + Classes.combos[$1] }
    var raise = zeros
    var valueCombos = 0
    for g in members where Double(valueCombos) < Double(totalCombos) / 3 {
      raise[g] = 1
      valueCombos += Classes.combos[g]
    }
    var bluffCombos = 0
    let candidates = Classes.bluffs.filter { continuing[$0] > 0 && raise[$0] == 0 }.sorted {
      equity[$0] != equity[$1] ? equity[$0] > equity[$1] : $0 < $1
    }
    for g in candidates where Double(bluffCombos) < Double(valueCombos) / 2 {
      raise[g] = 1
      bluffCombos += Classes.combos[g]
    }
    var call = zeros
    for g in members where raise[g] == 0 { call[g] = 1 }
    return (call, raise)
  }

  private func vector(of range: HandRange) -> ClassVector {
    HandClass.all.map { Double(range.weight(of: $0)) }
  }

  // MARK: Equity

  /// Equity of every class (a representative combo) against `villain`, Monte Carlo, in parallel.
  private func equities(versus villain: ClassVector, id: UInt64) -> [Double] {
    var weights = [Float](repeating: 0, count: 1326)
    for g in 0..<169 {
      for index in Classes.comboIndices[g] { weights[index] = Float(villain[g]) }
    }
    let range = HandRange(weights: weights)
    let out = SharedDoubles(count: 169)
    let base = StableSeed.mix(seed, id)
    let samples = self.samples
    DispatchQueue.concurrentPerform(iterations: 169) { g in
      var rng = SeededRNG(seed: StableSeed.mix(base, UInt64(g)))
      let result = EquityCalculator.monteCarlo(
        hero: Classes.hole[g], vs: [range], board: [], samples: samples, using: &rng)
      out.set(g, result.equity)
    }
    return out.values
  }

  // MARK: Export

  func export(into ranges: inout [String: HandRange]) {
    typealias Key = BaselinePreflopRanges.Key
    let hu = layout.headsUp
    func store(_ key: String, _ vector: ClassVector?) {
      guard let vector else { return }
      var weights: [HandClass: Float] = [:]
      for g in 0..<169 {
        let w = Float((vector[g] * 100).rounded() / 100)
        if w > 0 { weights[HandClass.all[g]] = w }
      }
      // Through the text form, so the exported range equals the one decoded from the generated source.
      let text = HandRange(classWeights: weights).text
      ranges[key] = (try? HandRange(parsing: text)) ?? HandRange(classWeights: weights)
    }
    for o in 0..<(count - 1) {
      let p = layout.seats[o].position
      store(Key.open(p, headsUp: hu), open[o])
      for d in (o + 1)..<count {
        let q = layout.seats[d].position
        store(Key.vsOpen(q, p, "call", headsUp: hu), defendCall[d][o])
        store(Key.vsOpen(q, p, "raise", headsUp: hu), defendRaise[d][o])
      }
      store(Key.vsThreeBet(p, "call", headsUp: hu), threeBetCall[o])
      store(Key.vsThreeBet(p, "raise", headsUp: hu), threeBetRaise[o])
    }
    store(Key.vsFourBet("call", headsUp: hu), fourBetCall)
    store(Key.vsFourBet("raise", headsUp: hu), fourBetRaise)
  }
}

/// Static per-class tables.
private enum Classes {
  static let combos: [Int] = HandClass.all.map(\.comboCount)
  static let comboIndices: [[Int]] = HandClass.all.map { $0.combos.map(\.index) }
  /// Share of the equity a class realises: 1 for the best hands, `1 - slope` for the worst.
  static let quality: [Double] = HandClass.all.map {
    1 - Solver.qualitySlope * PreflopOrdering.standard.percentile(of: $0)
  }
  static let hole: [[Card]] = HandClass.all.map { $0.combos[0].cards }
  static let bluffs: [Int] = Solver.bluffNames.compactMap { name in (try? HandClass(name))?.gridIndex }
}

/// Doubles written from concurrent iterations, each index by one iteration only.
private final class SharedDoubles: @unchecked Sendable {
  private let pointer: UnsafeMutablePointer<Double>
  private let count: Int

  init(count: Int) {
    self.count = count
    pointer = .allocate(capacity: count)
    pointer.initialize(repeating: 0, count: count)
  }

  deinit { pointer.deallocate() }

  func set(_ index: Int, _ value: Double) { pointer[index] = value }

  var values: [Double] { Array(UnsafeBufferPointer(start: pointer, count: count)) }
}
