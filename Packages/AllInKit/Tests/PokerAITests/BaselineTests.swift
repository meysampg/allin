  @Test func minimumDefenceFrequencyIsDefendedOverTheOwnRange() {
    // Facing a third-pot flop bet the hero continues with at least 60% of its own range.
    let base = baselineHeadsUpSpot(hole: "AhKd", board: "Kc7d2s", street: .flop, bet: 170)
    let own = DecisionContext(
      config: base.config, seat: base.seat, holeCards: [], board: base.board, street: base.street,
      button: base.button, smallBlindSeat: base.smallBlindSeat, bigBlindSeat: base.bigBlindSeat, seats: base.seats,
      pot: base.pot, history: base.history, legal: base.legal)
    var tables: [Int: BoardStrengthTable] = [:]
    let range = PerceivedRange.estimate(of: base.seat, in: own, blur: 0, tables: &tables)
    var config = BaselineConfig.default
    config.equitySamples = 24
    let strategy = BaselineStrategy(config: config)
    var weight = 0.0
    var continuing = 0.0
    for combo in Combo.all where combo.index % 7 == 0 {
      let w = Double(range[combo])
      if w <= 0 { continue }
      let d = strategy.distribution(for: baselineContext(base, hole: combo.cards))
      weight += w
      continuing += w * (1 - d.probability(of: .fold))
    }
    #expect(weight > 0)
    #expect(continuing / weight >= 0.6, "continue share \(continuing / weight)")
  }

  @Test func shortStackCallsAreAllIns() {
    // Facing a bet bigger than the stack: the only way to continue is all-in.
    var history = baselineHeadsUpSpot(hole: "AhKd", board: "Kc7d2s", street: .flop, bet: 600).history
    history[history.count - 1] = baselineEntry(0, .bet(to: 600), to: 600, street: .flop)
    let context = baselineContext(
      seatCount: 2, button: 0, hero: 1, hole: "AhKd", board: "Kc7d2s", street: .flop, pot: 1_100, history: history,
      currentBet: 600, heroStack: 300)
    #expect(context.legal.callIsAllIn)
    let d = BaselineStrategy().distribution(for: context)
    #expect(d.probability(of: .call) == 0)
    #expect(d.probability(of: .allIn) > 0.5)
  }

  @Test func shoveFacingRaiseUsesATightRange() {
    // A 100 bb shove over the hero's big blind: junk folds, premiums continue.
    let shove = [baselineEntry(0, .allIn, to: 10_000, allIn: true)]
    func spot(_ hole: String) -> DecisionContext {
      baselineContext(
        seatCount: 2, button: 0, hero: 1, hole: hole, street: .preflop, pot: 10_050, history: shove,
        currentBet: 10_000, heroCommitted: 100, lastRaiseSize: 9_900, heroStack: 9_900)
    }
    let strategy = BaselineStrategy()
    #expect(strategy.distribution(for: spot("7h2d")).probability(of: .fold) > 0.9)
    #expect(strategy.distribution(for: spot("AhAd")).probability(of: .fold) == 0)
  }

