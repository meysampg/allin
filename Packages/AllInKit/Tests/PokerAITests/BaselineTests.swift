  // MARK: Golden spots

  /// Six handed, button 0: seat 3 is under the gun and faces the blinds (50 and 100).
  private func underTheGun(_ hole: String) -> DecisionContext {
    baselineContext(
      seatCount: 6, button: 0, hero: 3, hole: hole, street: .preflop, pot: 150,
      history: [], currentBet: 100, heroStack: 10_000)
  }

  @Test func aces_unopened_neverFold() {
    for hole in ["AhAd", "AsAc", "AhAs"] {
      let d = BaselineStrategy().distribution(for: underTheGun(hole))
      #expect(d.probability(of: .fold) == 0)
      #expect(baselineProbability(d, where: baselineIsRaise) > 0.9)
    }
  }

  @Test func sevenDeuceFromUnderTheGunFolds() {
    var folds = 0.0
    for hole in ["7h2d", "7s2c", "2h7c"] {
      folds += BaselineStrategy().distribution(for: underTheGun(hole)).probability(of: .fold)
    }
    #expect(folds / 3 >= 0.95)
  }

  @Test func buttonOpensWiderThanUnderTheGun() {
    let button = baselineContext(
      seatCount: 6, button: 3, hero: 3, hole: "Jh9h", street: .preflop, pot: 150, history: [], currentBet: 100,
      heroStack: 10_000)
    let utg = baselineContext(
      seatCount: 6, button: 0, hero: 3, hole: "Jh9h", street: .preflop, pot: 150, history: [], currentBet: 100,
      heroStack: 10_000)
    let strategy = BaselineStrategy()
    let fromButton = baselineProbability(strategy.distribution(for: button), where: baselineIsRaise)
    let fromUtg = baselineProbability(strategy.distribution(for: utg), where: baselineIsRaise)
    #expect(fromButton > fromUtg)
  }

