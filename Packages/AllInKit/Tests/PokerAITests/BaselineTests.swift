/// Share of all 1326 combos in the union of `ranges` (class weights add up, capped at 1).
private func baselineShare(_ ranges: HandRange...) -> Double {
  var total = 0.0
  for combo in Combo.all {
    total += Double(min(1, ranges.reduce(Float(0)) { $0 + $1[combo] }))
  }
  return total / 1326
}

/// Plays `hands` random hands at 2...9 seats with mixed stacks and checks `strategy` at every decision.
private func baselineCheckPlayouts(_ strategy: BaselineStrategy, hands: Int, seed: UInt64) throws -> Int {
  var rng = SeededRNG(seed: seed)
  let random = UniformRandomStrategy()
  var decisions = 0
  for h in 0..<hands {
    let seatCount = 2 + h % 8
    let table = try TableConfig(seatCount: seatCount, smallBlind: 50, bigBlind: 100, chipUnit: 10)
    let stacks = (0..<seatCount).map { SeatStack(seat: $0, stack: 500 + 10 * Int(rng.next(upperBound: 950 as UInt64))) }
    var step = try HandReducer.start(config: table, button: h % seatCount, stacks: stacks, seed: UInt64(h) &+ seed)
    var records = step.records
    while let seat = step.state.seatToAct {
      let history = ActionEntry.entries(from: records)
      let context = DecisionContext.make(from: step.state, for: seat, history: history)!
      let distribution = strategy.distribution(for: context)
      try distribution.validate(against: context.legal)
      #expect(distribution.entries.allSatisfy { $0.probability > 0 })
      decisions += 1
      // The playout itself is random, so spots the bot would never reach are covered too.
      let action = random.distribution(for: context).sample(using: &rng)
      step = try HandReducer.apply(action, to: step.state)
      records += step.records
    }
  }
  return decisions
}

@Suite struct BaselineTests {
  // MARK: Generated ranges

  @Test func generatedRangesCoverEveryKeyAndHitTheSanityBands() {
    let ranges = BaselinePreflopRanges.generated
    let huOpen = ranges.open(.button, headsUp: true).totalWeight / 1326
    #expect((0.70...0.90).contains(huOpen), "heads-up button open \(huOpen)")
    let huBB = ranges.vsOpen(.bigBlind, opener: .button, headsUp: true)
    let huContinue = baselineShare(huBB.call, huBB.threeBet)
    #expect((0.55...0.75).contains(huContinue), "heads-up BB continue \(huContinue)")
    let early = ranges.open(.early, headsUp: false).totalWeight / 1326
    #expect((0.12...0.18).contains(early), "6-max early open \(early)")
    let button = ranges.open(.button, headsUp: false).totalWeight / 1326
    #expect((0.40...0.55).contains(button), "6-max button open \(button)")

    var previous = 0.0
    for p in [TablePosition.early, .middle, .cutoff, .button] {
      let share = ranges.open(p, headsUp: false).totalWeight / 1326
      #expect(share >= previous - 0.02, "opening widens towards the button")
      previous = share
    }
    #expect(ranges.open(.bigBlind, headsUp: false).totalWeight == 0)
    #expect(ranges.open(.bigBlind, headsUp: true).totalWeight == 0)
    for headsUp in [false, true] {
      let fourBet = ranges.vsFourBet(headsUp: headsUp)
      #expect(fourBet.call.totalWeight > 0 && fourBet.fiveBetAllIn.totalWeight > 0)
    }
    for p in [TablePosition.early, .middle, .cutoff, .button, .smallBlind] {
      let answer = ranges.vsThreeBet(p, headsUp: false)
      #expect(answer.call.totalWeight > 0 && answer.fourBet.totalWeight > 0)
      #expect(ranges.open(p, headsUp: false).totalWeight > 0)
    }
    // Defence against every opener behind it, for every position.
    for (i, p) in BaselinePreflopRanges.Key.order.enumerated() where i >= 1 {
      for o in BaselinePreflopRanges.Key.order[0..<min(i, 5)] {
        let d = ranges.vsOpen(p, opener: o, headsUp: false)
        #expect(d.call.totalWeight + d.threeBet.totalWeight > 0, "\(p) vs \(o)")
      }
    }
  }

  @Test func premiumsAreStrongestInTheRanges() throws {
    let ranges = BaselinePreflopRanges.generated
    let aa = Combo(baselineCards("AhAd")[0], baselineCards("AhAd")[1])
    let tripleSeven = try Combo("2c7d")
    #expect(ranges.open(.early, headsUp: false)[aa] == 1)
    #expect(ranges.open(.early, headsUp: false)[tripleSeven] == 0)
    #expect(ranges.vsOpen(.bigBlind, opener: .early, headsUp: false).threeBet[aa] >= 0.5)
    #expect(ranges.vsFourBet(headsUp: false).fiveBetAllIn[aa] >= 0.5)
  }

  @Test func swiftSourceIsStableAndChunked() {
    let ranges = BaselinePreflopRanges.generated
    let source = BaselineRangeModel.swiftSource(for: ranges)
    #expect(source == BaselineRangeModel.swiftSource(for: ranges))
    #expect(source.hasPrefix("// Generated by"))
    for line in source.split(separator: "\n") where line.hasPrefix("      \"") {
      #expect(line.count <= 6 + 90 + 3)
    }
    #expect(BaselineRangeModel.chunks(of: "") == [""])
    let long = (0..<60).map { _ in "A5s:0.5" }.joined(separator: ", ")
    let pieces = BaselineRangeModel.chunks(of: long)
    #expect(pieces.count > 1 && pieces.allSatisfy { $0.count <= 90 })
    #expect(pieces.joined(separator: ", ") == long)
  }

  @Test func generationIsDeterministicForAFixedSeed() {
    let a = BaselineRangeModel.generate(seed: 3, samplesPerClass: 6, rounds: 1)
    let b = BaselineRangeModel.generate(seed: 3, samplesPerClass: 6, rounds: 1)
    #expect(a == b)
    #expect(BaselineRangeModel.swiftSource(for: a) == BaselineRangeModel.swiftSource(for: b))
    let c = BaselineRangeModel.generate(seed: 4, samplesPerClass: 6, rounds: 1)
    #expect(c != a)
    #expect(a.open(.early, headsUp: false).totalWeight > 0)
  }

